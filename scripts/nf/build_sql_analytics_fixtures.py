"""Generate deterministic SI/UTC fixtures for the NF SQL analytics hook (#1649).

Expected results come only from the public pandas analytics functions, never
from SQL or JavaScript. --check compares exact deterministic generated bytes.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import pandas as pd

from open_fdd.analytics.core import (
    economizer_free_cooling_diagnostics, mech_cooling_oat_bins, motor_run_hours_weekly,
)
from open_fdd.analytics.weather_resolver import bas_vs_web_oat_stats

OUT = ROOT / 'tests/fixtures/sql_analytics_cases.json'


def clean(value):
    if isinstance(value, dict):
        return {str(k): clean(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean(v) for v in value]
    if isinstance(value, pd.Timestamp):
        return int(value.tz_localize('UTC').timestamp() * 1000) if value.tz is None else int(value.timestamp() * 1000)
    if value is None or value is pd.NA or value is pd.NaT:
        return None
    if hasattr(value, 'item'):
        return clean(value.item())
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def table(frame):
    return {'columns': list(frame.columns), 'rows': clean(frame.to_dict('records'))}


def frame(kind, index, columns):
    result = pd.DataFrame(columns, index=index)
    result.attrs['equipment_type'] = kind
    return result


def encode_frames(frames):
    return {key: {'equipment_type': value.attrs['equipment_type'],
                  'rows': [{'ts_ms': int(ts), **clean(row)} for ts, row in
                           zip(value.index.as_unit('ms').asi8, value.to_dict('records'))]}
            for key, value in frames.items()}


def decode_frames(case):
    result = {}
    for key, spec in case['frames'].items():
        rows = spec['rows']
        index = pd.to_datetime([row['ts_ms'] for row in rows], unit='ms', utc=True)
        columns = {role: [row[role] for row in rows] for role in rows[0] if role != 'ts_ms'}
        result[key] = frame(spec['equipment_type'], index, columns)
    return result


def expected(case):
    frames = decode_frames(case)
    roles = case['role_map']
    options = case.get('options', {})
    tool = case['tool']
    if tool == 'motor_run_hours_weekly':
        zone = options['timezone']
        starts = [pd.Timestamp(t, unit='ms', tz='UTC').tz_convert(zone) for t in options['week_starts']]
        occupied = [(pd.Timestamp(a, unit='ms', tz='UTC'), pd.Timestamp(b, unit='ms', tz='UTC'))
                    for a, b in options['occupied_intervals']]
        answer = motor_run_hours_weekly(frames, roles, include_all_mapped=True,
                                        week_starts=starts, occupied_intervals=occupied)
        return table(answer.sort_values(['equipment_id', 'signal', 'week_start']).reset_index(drop=True))
    if tool == 'mech_cooling_oat_bins':
        answer = mech_cooling_oat_bins(frames, roles, include_total=False)
        return table(answer.sort_values(['equipment_id', 'bin_start']).reset_index(drop=True))
    if tool == 'economizer_free_cooling_diagnostics':
        answer = economizer_free_cooling_diagnostics(frames, roles)
        metrics = answer['metrics']
        if not metrics.empty:
            metrics = metrics.sort_values('equipment_id').reset_index(drop=True)
        return {'metrics': table(metrics), 'skipped': clean(answer['skipped'])}
    if tool == 'bas_vs_web_oat_stats':
        web = case['web_weather']
        series = pd.Series([r['value_c'] for r in web],
                           index=pd.to_datetime([r['ts_ms'] for r in web], unit='ms', utc=True), dtype=float)
        return clean({key: bas_vs_web_oat_stats(df['outside-air-temp'], series,
                                               max_age_seconds=options['max_age_seconds'])
                      for key, df in frames.items()})
    raise ValueError(tool)


def build_cases():
    cases = []

    def add(name, tool, frames, **extra):
        case = {'id': name, 'tool': tool, 'frames': encode_frames(frames),
                'role_map': {key: {role: role for role in df.columns} for key, df in frames.items()}, **extra}
        case['expected'] = expected(case)
        cases.append(case)

    start = pd.Timestamp('2026-03-02', tz='America/Chicago')
    end = pd.Timestamp('2026-03-09', tz='America/Chicago')
    hours = pd.date_range(start.tz_convert('UTC'), end.tz_convert('UTC'), freq='h')
    hours = hours.delete(50)  # A 2-hour gap is unknown; it must not be clipped to one hour.
    ms = lambda t: int(t.timestamp() * 1000)
    add('runtime-dst-week-gap-percent-command', 'motor_run_hours_weekly', {
        'equipment-1': frame('AHU', hours, {'fan-status': 1.0, 'fan-cmd': 0.0, 'outside-air-temp': 12.0}),
        'equipment-2': frame('BOILER', hours, {'hw-pump-cmd': [100.0 if i % 2 else 0.0 for i in range(len(hours))]}),
    }, options={'timezone': 'America/Chicago', 'week_starts': [ms(start), ms(end)],
                'occupied_intervals': [[ms(start + pd.Timedelta(hours=8)), ms(start + pd.Timedelta(hours=17))]]})

    index = pd.date_range('2026-07-06', periods=13, freq='5min', tz='UTC')
    oat = [8., 10., 12., 16., 18., 22., 26., 28., 30., 32., 34., 36., 38.]
    add('cooling-individual-percent-and-heat-pump-mode', 'mech_cooling_oat_bins', {
        'equipment-1': frame('AHU', index, {'compressor-status': 0., 'compressor-cmd': 100., 'outside-air-temp': oat}),
        'equipment-2': frame('HP', index, {'compressor-status': 1.,
            'heat-pump-cooling-status': [0.] * 6 + [1.] * 7, 'outside-air-temp': oat}),
        'equipment-3': frame('RTU', index, {'compressor-stage-1': [0., 1.] * 6 + [0.],
            'compressor-stage-2': [1., 0.] * 6 + [1.], 'outside-air-temp': oat}),
    })

    common = {'fan-status': [1.] * 10 + [0.] * 3, 'outside-air-temp': [10.] * 13,
              'return-air-temp': [22.] * 13, 'outside-air-damper': [25.] * 13}
    add('economizer-percent-damper-mat-holes', 'economizer_free_cooling_diagnostics', {
        'equipment-1': frame('AHU', index, {**common, 'mixed-air-temp': [None if i % 4 == 0 else 19. for i in range(13)]}),
    })
    add('economizer-missing-mat', 'economizer_free_cooling_diagnostics', {
        'equipment-1': frame('AHU', index, common),
    })

    weather_index = pd.date_range('2026-07-06', periods=37, freq='10min', tz='UTC')
    web = [{'ts_ms': int(t), 'value_c': 20.} for i, t in enumerate(weather_index.as_unit('ms').asi8) if i < 6 or i >= 30]
    for name, observations in [('web-weather-outage', web), ('web-weather-empty', [])]:
        add(name, 'bas_vs_web_oat_stats', {
            'equipment-1': frame('AHU', weather_index, {'outside-air-temp': 21.5}),
        }, web_weather=observations, options={'max_age_seconds': 1200})
    return {'schema_version': 1, 'source': 'repository pandas analytics; deterministic synthetic data only',
            'timestamp_unit': 'UTC epoch milliseconds',
            'units': {'temperature': 'degC', 'temperature_difference': 'degC', 'commands': 'percent 0-100',
                      'motor_status': 'boolean 0-1', 'duration': 'hours'},
            'note': 'Legacy pandas output names ending _f contain SI temperatures/deltas; no Fahrenheit conversion.',
            'cases': cases}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=OUT)
    args = parser.parse_args()
    content = json.dumps(build_cases(), indent=2, sort_keys=True, allow_nan=False) + '\n'
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding='utf-8') != content:
            print('SQL analytics fixtures are stale; run scripts/nf/build_sql_analytics_fixtures.py', file=sys.stderr)
            return 1
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding='utf-8')
    print(f'SQL analytics fixtures: {"checked" if args.check else "generated"} 6 cases')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
