#!/usr/bin/env python3
"""Render nf-app/static/fdd-catalog.json into docs/fdd-rules.md (the FDD rules reference page).

    python3 scripts/nf/gen_rule_docs.py            # write docs/fdd-rules.md
    python3 scripts/nf/gen_rule_docs.py --check    # exit 1 if the committed page is stale

Parameter values are SI (the catalog stores SI defaults). Units come from sql/fdd/tuning_catalog.json
when that file is present; a parameter without a known unit is shown as a bare number.
Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "nf-app" / "static" / "fdd-catalog.json"
TUNING = ROOT / "sql" / "fdd" / "tuning_catalog.json"
OUT = ROOT / "docs" / "fdd-rules.md"

UNIT_LABEL = {
    "degC": "°C", "degC_delta": "K (delta)", "degC_delta_per_h": "K/h", "pct": "%", "frac": "(0-1)",
    "min": "min", "sec": "s", "h": "h", "L_per_s": "L/s", "Pa": "Pa", "kWh": "kWh", "ppm": "ppm",
    "bool": "(0/1)", "count": "count", "x": "x", "unit": "", "%": "%",
}

HEADER = """---
title: FDD rules
nav_order: 7
---

# FDD rules

<!-- GENERATED by scripts/nf/gen_rule_docs.py from nf-app/static/fdd-catalog.json. Do not edit by hand. -->

This generated index summarizes the production SQL rules and their default parameters. See
[Writing SQL rules](sql-rules.html), [Writing pandas rules](pandas-rules.html), and the generated
[SQL cookbook](rules/sql-cookbook.html) for implementation details.

- **Roles** are the inputs a rule needs, named after NF point classes / Haystack markers. A rule runs only when
  every *required* role is bound; *optional* roles refine the result.
- **Equipment kinds** are the Haystack equipment kinds a rule applies to (empty = any equipment).
- `confirm` is how long a condition must hold before it counts as a fault.
- Each rule id links to its entry in the [SQL cookbook](rules/sql-cookbook.html).

Regenerate this page with `python3 scripts/nf/gen_rule_docs.py` (`--check` fails when it is stale).

| Rule | Description | Equipment kinds | Required roles | Optional roles | Parameters (SI) |
|---|---|---|---|---|---|
"""


def load_units() -> dict:
    if not TUNING.is_file():
        return {}
    data = json.loads(TUNING.read_text(encoding="utf-8"))
    out = {}
    for r in data.get("rules", []):
        out[r.get("rule_id", "")] = {k: (v or {}).get("unit", "") for k, v in (r.get("parameters") or {}).items()}
    return out


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def fmt_value(v) -> str:
    if isinstance(v, float):
        return f"{v:.6g}"
    return str(v)


def fmt_params(params: dict, units: dict) -> str:
    items = []
    for k in sorted(params):
        if k == "confirm_seconds":
            continue
        label = UNIT_LABEL.get(units.get(k, ""), units.get(k, ""))
        items.append(f"`{k}` = {fmt_value(params[k])}{(' ' + label) if label else ''}")
    return "<br>".join(cell(i) for i in items) if items else "none"


def render() -> str:
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    units = load_units()
    rules = sorted(cat["rules"], key=lambda r: r["id"])
    lines = [HEADER.format(n=len(rules))]
    for r in rules:
        kinds = ", ".join(r.get("equipment_kinds") or []) or "any"
        req = ", ".join(f"`{x}`" for x in r.get("required_roles") or []) or "none"
        opt = ", ".join(f"`{x}`" for x in r.get("optional_roles") or []) or "none"
        confirm = r.get("confirm_seconds") or 0
        desc = cell(r.get("description", ""))
        if confirm:
            desc += f" (confirm {confirm // 60} min)" if confirm % 60 == 0 else f" (confirm {confirm} s)"
        params = fmt_params(r.get("parameters") or {}, units.get(r["id"], {}))
        lines.append(f"| [**{cell(r['id'])}**](rules/sql-cookbook.html#{r['id'].lower()}) ({cell(r.get('priority', ''))}) | {desc} | {cell(kinds)} | {req} | {opt} | {params} |\n")
    return "".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/fdd-rules.md is not up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/fdd-rules.md is stale: run python3 scripts/nf/gen_rule_docs.py", file=sys.stderr)
            return 1
        print("docs/fdd-rules.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
