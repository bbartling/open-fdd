#!/usr/bin/env python3
"""Render the Rules landing page and rule catalog, docs/rules/index.md.

    python3 scripts/nf/gen_rule_docs.py            # write docs/rules/index.md
    python3 scripts/nf/gen_rule_docs.py --check    # exit 1 if the committed page is stale

Reads nf-app/static/fdd-catalog.json (rule ids, descriptions, equipment kinds, confirm time) and the parity facts in
docs_units.py (tests/parity NO_TWIN and open_fdd/data/parity_known_differences.json). The per-rule inputs, parameters and
unit tables are in the cookbooks (gen_cookbook.py). Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from docs_units import cell, parity_status, read_parity  # noqa: E402

CATALOG = ROOT / "nf-app" / "static" / "fdd-catalog.json"
OUT = ROOT / "docs" / "rules" / "index.md"

HEADER = """---
title: Rules
nav_order: 1
has_children: true
permalink: /rules/
---

# Rules

<!-- GENERATED by scripts/nf/gen_rule_docs.py from nf-app/static/fdd-catalog.json. Do not edit by hand. -->

Open-FDD ships **{n} SQL fault and analytics rules**, **{twins} with a pandas twin**. A rule reads Haystack roles bound to NF
points by the [data model](../modeling.html), computes in SI, and writes its result as NF points. Every entry states the unit of
each input, parameter and output.

| Page | Use it to |
|---|---|
| [SQL cookbook](sql-cookbook.html) | See each rule's inputs, parameters, outputs and parity |
| [Pandas cookbook](pandas-cookbook.html) | Run the same rules in Python |
| [Using SQL rules outside Open-FDD](borrowing-sql.html) | Run a rule on SQLite, Postgres, DuckDB or Timescale |
| [Parity](parity.html) | See where pandas and SQL agree |
| [Parity harness](parity-harness.html) | Prove it on your own database |
| [Writing SQL rules](../sql-rules.html) | Add or change a rule |

## Catalog

- A rule runs when every required role is bound. `confirm` is how long a condition must hold before it counts.
- Equipment kinds are Haystack equipment kinds; none means any equipment.
- Parity is pandas SI against SQL SI ([details](parity.html)).

| Rule | What it checks | Equipment | Confirm | Twin | Parity |
|---|---|---|---|---|---|
"""


def confirm_text(seconds: int) -> str:
    if not seconds:
        return "immediate"
    return f"{seconds // 60} min" if seconds % 60 == 0 else f"{seconds} s"


def render() -> str:
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    known, _other, no_twin = read_parity()
    rules = sorted(cat["rules"], key=lambda r: r["id"])
    lines = [HEADER.format(n=len(rules), twins=len(rules) - len(no_twin))]
    for r in rules:
        rid = r["id"]
        kinds = ", ".join(r.get("equipment_kinds") or []) or "any"
        twin = "SQL only" if rid in no_twin else f"[pandas](pandas-cookbook.html#{rid.lower()})"
        lines.append(f"| [**{cell(rid)}**](sql-cookbook.html#{rid.lower()}) | {cell(r.get('description', ''))} | {cell(kinds)} | "
                     f"{confirm_text(r.get('confirm_seconds') or 0)} | {twin} | {parity_status(rid, known, no_twin)} |\n")
    return "".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/rules/index.md is not up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/rules/index.md is stale: run python3 scripts/nf/gen_rule_docs.py", file=sys.stderr)
            return 1
        print("docs/rules/index.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
