#!/usr/bin/env python3
"""Generate the copies and the catalog of the shared Open-FDD core schema.

The one source is sql/fdd/schema/core.sql (tables fdd.point, fdd.rule_result, fdd.rule_config). This script

  * copies it byte for byte to nf-app/timescale/core.sql (installed by the NF app) and open_fdd/data/core.sql
    (shipped in the wheel, so a downstream test compares its vendored copy against the installed package), and
  * writes sql/fdd/schema/core.catalog.json: the normalized catalog (columns, types, defaults, constraints, indexes)
    that Postgres reports after executing the file (run in PGlite, needs the nf-app npm dependencies), plus its sha256.

    python scripts/nf/build_core_schema.py           # write
    python scripts/nf/build_core_schema.py --check   # exit 1 when a copy or the catalog is stale (CI)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "sql/fdd/schema/core.sql"
COPIES = [ROOT / "nf-app/timescale/core.sql", ROOT / "open_fdd/data/core.sql"]
CATALOG = ROOT / "sql/fdd/schema/core.catalog.json"
HELPER = ROOT / "scripts/nf/core_catalog.mjs"


def lf(data: bytes) -> bytes:
    """Line endings normalized: git may check the files out as CRLF on Windows; the content is what matters."""
    return data.replace(b"\r\n", b"\n")


def source_bytes() -> bytes:
    return lf(SOURCE.read_bytes())


def sha256_of(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def pg_catalog(sql_path: Path) -> dict:
    """Normalized catalog Postgres (PGlite) reports after executing sql_path."""
    node = shutil.which("node")
    if not node:
        raise RuntimeError("node is required (PGlite from the nf-app dependencies)")
    proc = subprocess.run([node, str(HELPER), str(sql_path)], capture_output=True, text=True, encoding="utf-8", cwd=ROOT)
    if proc.returncode != 0:
        raise RuntimeError(f"core_catalog.mjs failed:\n{proc.stdout}\n{proc.stderr}")
    return json.loads(proc.stdout)


def render_catalog() -> str:
    doc = {
        "_doc": "Generated by scripts/nf/build_core_schema.py: the catalog Postgres reports after executing "
                "sql/fdd/schema/core.sql. Downstream applications compare their database to this, table by table.",
        "core_sql_sha256": sha256_of(source_bytes()),
        "tables": {k: v for k, v in pg_catalog(SOURCE).items() if k.startswith("fdd.")},
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if a copy or the catalog is stale")
    args = ap.parse_args(argv)
    data = source_bytes()
    stale = []
    for dst in COPIES:
        if dst.is_file() and lf(dst.read_bytes()) == data:
            continue
        stale.append(dst.relative_to(ROOT).as_posix())
        if not args.check:
            dst.write_bytes(data)
            print(f"wrote {dst.relative_to(ROOT).as_posix()}")
    catalog = render_catalog().encode("utf-8")
    if not CATALOG.is_file() or lf(CATALOG.read_bytes()) != catalog:
        stale.append(CATALOG.relative_to(ROOT).as_posix())
        if not args.check:
            CATALOG.write_bytes(catalog)
            print(f"wrote {CATALOG.relative_to(ROOT).as_posix()}")
    if args.check:
        if stale:
            print("stale core schema files (run: python scripts/nf/build_core_schema.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("core schema copies and catalog are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
