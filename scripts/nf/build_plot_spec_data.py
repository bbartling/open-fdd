#!/usr/bin/env python3
"""Generate ``nf-app/static/plot-spec-data.js`` from the plot-spec data in ``open_fdd/data/``.

The static app does not fetch JSON at runtime: ``plot-spec.js`` reads the preset registry, units and palette from this
generated classic script / CommonJS module.

    open_fdd/data/rcx_presets.json  ->  presets
    open_fdd/data/units.json        ->  units
    open_fdd/data/palette.json      ->  palette
    open_fdd/data/sensor_sweep_limits.json -> sweep_limits (the FDD tab's browser estimate of the SV lanes)

    python scripts/nf/build_plot_spec_data.py            # write
    python scripts/nf/build_plot_spec_data.py --check    # exit 1 when stale (CI)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {"presets": "open_fdd/data/rcx_presets.json", "units": "open_fdd/data/units.json", "palette": "open_fdd/data/palette.json",
           "sweep_limits": "open_fdd/data/sensor_sweep_limits.json"}
OUT = "nf-app/static/plot-spec-data.js"


def rule_tuning_payload() -> dict:
    cat = json.loads((ROOT / "sql" / "fdd" / "tuning_catalog.json").read_text(encoding="utf-8"))
    rules = {}
    for r in cat["rules"]:
        controls = {}
        for k, d in r["parameters"].items():
            if not d.get("effect_in_sql", True):
                continue
            item = {
                "key": k,
                "kind": d["kind"],
                "label": d["label"],
                "min": d["min"],
                "max": d["max"],
                "step": d["step"],
                "unit": d["unit"],
                "default": d["default"],
            }
            if d.get("description"):
                item["description"] = d["description"]
            controls[k] = item
        rules[r["rule_id"]] = {"controls": controls}
    return {"version": 1, "rules": rules}


def render() -> str:
    doc = {k: json.loads((ROOT / v).read_text(encoding="utf-8")) for k, v in SOURCES.items()}
    doc["rule_tuning"] = rule_tuning_payload()
    body = json.dumps(doc, separators=(",", ":"), ensure_ascii=False)
    return (
        "// GENERATED by scripts/nf/build_plot_spec_data.py from open_fdd/data/{rcx_presets,units,palette,sensor_sweep_limits}.json. Do not edit.\n"
        "// Classic script (global ofddPlotSpecData) and CommonJS; read by plot-spec.js.\n"
        "(function (root) {\n"
        f"  const data = {body};\n"
        "  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n"
        "  root.ofddPlotSpecData = data;\n"
        "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the generated file is stale")
    args = ap.parse_args(argv)
    want = render().encode("utf-8")
    dst = ROOT / OUT
    have = dst.read_bytes().replace(b"\r\n", b"\n") if dst.is_file() else None
    if have == want:
        print("plot-spec data is up to date")
        return 0
    if args.check:
        print(f"stale {OUT} (run: python scripts/nf/build_plot_spec_data.py)", file=sys.stderr)
        return 1
    dst.write_bytes(want)
    print(f"updated {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
