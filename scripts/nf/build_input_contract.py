#!/usr/bin/env python3
"""Generate the standalone scratch DDL and compatibility role-scale map.

The canonical source is sql/fdd/input_contract.json. This scratch schema is
engine-independent and separate from any operational database migration.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from input_contract import ROOT, load_source, postgres_type

DDL = ROOT / "sql/fdd/input_contract.sql"
SCALE_VIEW = ROOT / "sql/fdd/role_scales.json"
SCALE_DOC = (
    "Generated compatibility view of input_contract.json roles. fraction = 0-1, boolean = 0/1, "
    "percent_rh = 0-100, text = categorical string, si:<unit> = physical SI value. "
    "Scale definitions live in input_contract.json."
)


def render_ddl(contract: dict) -> str:
    """Render clean-session temporary tables from the canonical table declarations."""
    lines = [
        "-- Generated by scripts/nf/build_input_contract.py from input_contract.json.",
        "-- Scratch contract only; do not execute as an operational migration.",
        "-- Supply SI values directly: degC, Pa, L/s, kW, kWh, A, ppm, count.",
        "-- Fraction commands are 0-1; boolean samples are 0/1; relative humidity is 0-100 %RH.",
        "-- Only relations a rendered rule reads are declared (contract version 2 dropped authorized_series / equipment).",
    ]
    for table, columns in contract["_normalized_tables"].items():
        ddl_columns = ", ".join(f'"{column["name"]}" {postgres_type(column["type"])}' for column in columns)
        lines.append(f"CREATE TEMP TABLE {table} ({ddl_columns});")
    return "\n".join(lines) + "\n"


def render_scales(contract: dict) -> str:
    """Render role_scales.json as a compatibility view for existing tooling."""
    roles = {name: spec["scale"] for name, spec in sorted(contract["roles"].items())}
    return json.dumps({"_doc": SCALE_DOC, "roles": roles}, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated compatibility files are stale")
    args = parser.parse_args()
    contract = load_source()
    generated = {DDL: render_ddl(contract), SCALE_VIEW: render_scales(contract)}
    stale = []
    for path, contents in generated.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != contents:
            if args.check:
                stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.write_text(contents, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("generated scratch contract files are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("scratch contract DDL and role scale compatibility view are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
