#!/usr/bin/env python3
"""Generate the 223P role file, the input-name list and the NF role binding.

The vocabulary is ``roles/openfdd-roles.json`` (1.1.0-draft.1). 223P is the core:
each role is a pattern (property class, medium, aspect, quantity kind, connection
point) in ``sql/fdd/roles-223p.ttl``, which ``owl:imports`` 223P. Haystack is an
overlay on the same role (NF class, markers, unit symbol) in the binding JSON.

``input_names_223p.json`` is the role names read back from that Turtle.

    python3 scripts/nf/gen_roles_223p.py
    python3 scripts/nf/gen_roles_223p.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VOCAB = ROOT / "roles" / "openfdd-roles.json"
TTL = ROOT / "sql" / "fdd" / "roles-223p.ttl"
NAMES = ROOT / "sql" / "fdd" / "input_names_223p.json"
ROLE_RE = re.compile(r"^ofdd:([A-Za-z0-9_]+) a ofdd:PointRole ;", re.M)

S223_FIELDS = (
    ("property_class", "ofdd:propertyClass"),
    ("scope", "ofdd:scope"),
    ("equipment_role", "ofdd:equipmentRole"),
    ("equipment_medium", "ofdd:equipmentMedium"),
    ("equipment", "ofdd:equipment"),
    ("roles", "ofdd:connectionRole"),
    ("connection_point", "ofdd:connectionPoint"),
    ("medium", "ofdd:medium"),
    ("constituent", "ofdd:constituent"),
    ("qualifier", "ofdd:qualifier"),
    ("quantity_kind", "ofdd:quantityKind"),
    ("enumeration_kind", "ofdd:enumerationKind"),
    ("aspects", "ofdd:aspect"),
    ("applies_to", "ofdd:appliesTo"),
)

VENDORS = (
    ROOT / "nf-app" / "static" / "roles",
    ROOT / "lite" / "static" / "roles",
)


def _curie(term: str) -> str:
    # g36: is a vocabulary extension token (not a 223P IRI and not a Haystack tag).
    if term.startswith(("s223:", "ext:", "g36:", "quantitykind:", "unit:")):
        return term
    raise ValueError(f"role term is not a 223P, extension, quantity kind or unit CURIE: {term}")


def _terms(value) -> list[str]:
    if value is None or value == "":
        return []
    if isinstance(value, list):
        return [_curie(str(item)) for item in value if item]
    return [_curie(str(value))]


def _ttl_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_ttl(vocab: dict) -> str:
    lines = [
        "# Generated by scripts/nf/gen_roles_223p.py from roles/openfdd-roles.json.",
        "# 223P is the core (owl:imports). Haystack is not in this file; the binding JSON is the overlay.",
        f"# vocabulary {vocab['vocabulary']} {vocab['version']}",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "@prefix s223: <http://data.ashrae.org/standard223#> .",
        "@prefix unit: <http://qudt.org/vocab/unit/> .",
        "@prefix quantitykind: <http://qudt.org/vocab/quantitykind/> .",
        "@prefix ext: <urn:openfdd:ext#> .",
        "@prefix g36: <http://data.ashrae.org/standard223/1.0/extensions/g36#> .",
        "@prefix ofdd: <urn:openfdd:role#> .",
        "",
        f"<urn:openfdd:roles/{vocab['version']}> a owl:Ontology ;",
        f"    rdfs:label \"Open-FDD point roles {vocab['version']}\" ;",
        f"    owl:versionInfo {_ttl_string(vocab['version'])} ;",
        "    owl:imports <http://data.ashrae.org/standard223/1.0/model/all> .",
        "",
        "ofdd:PointRole a owl:Class ; rdfs:label \"point role\" .",
        "ofdd:propertyClass a owl:AnnotationProperty .",
        "ofdd:scope a owl:AnnotationProperty .",
        "ofdd:equipmentRole a owl:AnnotationProperty .",
        "ofdd:equipmentMedium a owl:AnnotationProperty .",
        "ofdd:equipment a owl:AnnotationProperty .",
        "ofdd:connectionRole a owl:AnnotationProperty .",
        "ofdd:connectionPoint a owl:AnnotationProperty .",
        "ofdd:medium a owl:AnnotationProperty .",
        "ofdd:constituent a owl:AnnotationProperty .",
        "ofdd:qualifier a owl:AnnotationProperty .",
        "ofdd:quantityKind a owl:AnnotationProperty .",
        "ofdd:enumerationKind a owl:AnnotationProperty .",
        "ofdd:aspect a owl:AnnotationProperty .",
        "ofdd:appliesTo a owl:AnnotationProperty .",
        "ofdd:grounding a owl:AnnotationProperty .",
        "ofdd:unit a owl:AnnotationProperty .",
        "ofdd:ruleInput a owl:AnnotationProperty .",
        "ofdd:writable a owl:AnnotationProperty .",
        "",
    ]
    for role in vocab["roles"]:
        name = role["role"]
        body = [f"ofdd:{name} a ofdd:PointRole ;",
                f"    rdfs:label {_ttl_string(name)} ;",
                f"    ofdd:grounding {_ttl_string(role['grounding'])} ;"]
        pattern = role.get("s223") or {}
        for key, pred in S223_FIELDS:
            for term in _terms(pattern.get(key)):
                body.append(f"    {pred} {term} ;")
        unit = role.get("unit")
        if unit:
            body.append(f"    ofdd:unit {_curie(unit)} ;")
        body.append(f"    ofdd:ruleInput {'true' if role.get('rule_input') else 'false'} ;")
        body.append(f"    ofdd:writable {_ttl_string(role.get('writable') or 'never')} .")
        lines.extend(body)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def names_from_ttl(text: str) -> list[str]:
    return ROLE_RE.findall(text)


def render_names(vocab: dict, ttl: str) -> str:
    names = names_from_ttl(ttl)
    if names != [role["role"] for role in vocab["roles"]]:
        raise ValueError("role names read back from the Turtle do not match the vocabulary")
    payload = {
        "source": "sql/fdd/roles-223p.ttl",
        "vocabulary": vocab["vocabulary"],
        "version": vocab["version"],
        "names": names,
    }
    return json.dumps(payload, indent=2) + "\n"


def _binding_row(role: dict) -> dict:
    hay = role.get("haystack") or {}
    unit = role.get("unit")
    return {
        "iri": f"urn:openfdd:role#{role['role']}",
        "name": role["role"],
        "required": bool(role.get("rule_input")),
        "unit": unit.split(":", 1)[-1] if unit else None,
        "si": hay.get("unit"),
        "value_type": role.get("value_type"),
        "writable": role.get("writable") or "never",
        "nf": {
            "classes": list(hay.get("classes") or []),
            "markers": list(hay.get("markers") or []),
            "alt_markers": list(hay.get("alt_markers") or []),
            "custom_markers": list(hay.get("custom_markers") or []),
            "optional": list(hay.get("optional") or []),
            "forbid": list(hay.get("forbid") or []),
            "equip_markers": list(hay.get("equip_markers") or []),
            "equip_forbid": list(hay.get("equip_forbid") or []),
            "binding_scope": hay.get("binding_scope") or "own",
        },
    }


def render_binding(vocab: dict) -> str:
    payload = {
        "vocabulary": vocab["vocabulary"],
        "version": vocab["version"],
        "source": "roles/openfdd-roles.json",
        "note": "223P patterns are in roles-223p.ttl. This file is the Haystack overlay: NF class, markers, SI unit, required.",
        "roles": [_binding_row(role) for role in vocab["roles"]],
    }
    return json.dumps(payload, indent=2) + "\n"


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _box_vocab(vocab_text: str) -> str:
    """The box copy drops ``$schema``. That relative file is not in the app."""
    return "".join(line for line in vocab_text.splitlines(keepends=True) if '"$schema"' not in line)


def vendor_files(vocab_text: str, ttl: str, binding: str) -> dict[str, str]:
    shipped = _box_vocab(vocab_text)
    digest = "\n".join([
        f"{_sha256(shipped)}  openfdd-roles.json",
        f"{_sha256(binding)}  role-binding.json",
        f"{_sha256(ttl)}  roles-223p.ttl",
        "",
    ])
    return {
        "openfdd-roles.json": shipped,
        "role-binding.json": binding,
        "roles-223p.ttl": ttl,
        "roles.sha256": digest,
    }


def build() -> dict[str, str]:
    vocab_text = VOCAB.read_text(encoding="utf-8")
    vocab = json.loads(vocab_text)
    if vocab.get("version") != "1.1.0-draft.1":
        raise ValueError(f"expected roles vocabulary 1.1.0-draft.1, got {vocab.get('version')}")
    ttl = render_ttl(vocab)
    binding = render_binding(vocab)
    return {
        "ttl": ttl,
        "names": render_names(vocab, ttl),
        "binding": binding,
        "vendor": vendor_files(vocab_text, ttl, binding),
        "vocab_text": vocab_text,
    }


def outputs(built: dict[str, str]) -> dict[Path, str]:
    files = {TTL: built["ttl"], NAMES: built["names"]}
    for directory in VENDORS:
        for name, text in built["vendor"].items():
            files[directory / name] = text
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file differs")
    args = parser.parse_args(argv)
    try:
        built = build()
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"gen_roles_223p: {exc}", file=sys.stderr)
        return 1
    stale = []
    for path, text in outputs(built).items():
        payload = text.encode("utf-8")
        current = path.read_bytes() if path.is_file() else None
        if current != payload:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(payload)
    if args.check and stale:
        print("gen_roles_223p: stale files:", file=sys.stderr)
        for path in stale:
            print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    print(f"gen_roles_223p: {len(json.loads(built['names'])['names'])} roles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
