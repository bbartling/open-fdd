def test_templates_reproduce_the_renderer():
    shipped = cat.load_role_limits()
    for rid in o.SWEEP_RULES:
        t = render_rule.render_template(rid)
        assert render_rule.sentinel(t["fragment"]) in t["sql"]
        assert render_rule.fill_template(t["sql"], rid, t["values"], t["sql_roles"], shipped) == render_rule.render(rid)
        over = o.effective_role_limits(site=CASES[1]["site"], equipment=CASES[1]["equipment"])
        assert render_rule.fill_template(t["sql"], rid, t["values"], t["sql_roles"], over) == render_rule.render(rid, role_limits=over)
    pack = json.loads((ROOT / "nf-app" / "rules" / "pack-postgres.json").read_text(encoding="utf-8"))
    assert set(pack["role_limit_templates"]["rules"]) == set(o.SWEEP_RULES)
    assert pack["role_limit_templates"]["rule_config_id"] == o.LIMITS_RULE_ID


class _Cursor:
    """Tiny in-memory stand-in for fdd.rule_config (the SQL is exercised for real in the Timescale suite)."""

    def __init__(self):
        self.rows, self._result = [], []

    def execute(self, sql, args=()):
        s = " ".join(sql.split())
        if s.startswith("SELECT scope_key, revision, parameters"):
            self._result = [(r["scope"], r["rev"], r["params"]) for r in self.rows if r["site"] == args[0] and r["active"]]
        elif s.startswith("SELECT pg_advisory_xact_lock"):
            self._result = [(None,)]
        elif s.startswith("SELECT coalesce(max(revision)"):
            self._result = [(max([r["rev"] for r in self.rows if r["site"] == args[0] and r["scope"] == args[2]], default=0) + 1,)]
        elif s.startswith("UPDATE fdd.rule_config"):
            for r in self.rows:
                if r["site"] == args[0] and r["scope"] == args[2]:
                    r["active"] = False
        elif s.startswith("INSERT INTO fdd.rule_config"):
            self.rows.append({"site": args[0], "scope": args[2], "rev": args[3], "params": json.loads(args[4]), "active": True, "by": args[5]})
        elif s.startswith("SELECT parameters FROM"):
            self._result = [(r["params"],) for r in self.rows if r["site"] == args[0] and r["scope"] == args[2] and r["rev"] == args[3]]
        else:
            raise AssertionError(s)

    def fetchall(self):
        return self._result

    def fetchone(self):
        return self._result[0] if self._result else None


def test_store_appends_revisions_resets_and_rolls_back():
    cur = _Cursor()
    assert o.save_override(cur, "s1", "site", {"version": 1, "roles": {"zone-air-temp": {"hi": 30.0}}}, "t") == 1
    with pytest.raises(ValueError):
        o.save_override(cur, "s1", "equip:A", {"version": 1, "roles": {"zone-air-temp": {"lo": 31.0}}}, "t")   # over the site's 30
    assert len(cur.rows) == 1, "an invalid override is never stored"
    assert o.save_override(cur, "s1", "site", {"version": 1, "roles": {"zone-air-temp": {"hi": 28.0}}}, "t") == 2
    assert o.reset_override(cur, "s1", "site", "t") == 3
    assert o.rollback_override(cur, "s1", "site", 1, "t") == 4
    active = o.active_overrides(cur, "s1")
    assert active["site"]["revision"] == 4
    assert active["site"]["parameters"]["roles"] == {"zone-air-temp": {"hi": 30.0}}
    assert active["site"]["parameters"]["rollback_of"] == 1
    assert [r["active"] for r in cur.rows] == [False, False, False, True]
    with pytest.raises(ValueError):
        o.save_override(cur, "s1", "building", {"version": 1, "roles": {}}, "t")


