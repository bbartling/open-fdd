//! Typed security audit events (`openfdd.audit.v1`).
//!
//! Each sensitive operation builds one [`AuditEvent`] and emits it after the
//! result is known, including error paths. Fields are an allowlist: identifiers,
//! enums, and counts. Request bodies, headers, tokens, and passwords are never
//! fields. Every string goes through [`open_fdd_edge_prototype::auth::redact`]
//! with a fixed budget, and the serialized event is bounded by [`MAX_EVENT_BYTES`].
//!
//! The sink is still `open_fdd_edge_prototype::auth::audit::log_event`;
//! [`AuditEvent::emit`] is the only call into it from this module, so the writer
//! can be replaced without touching handlers.

use std::future::Future;
use std::sync::{Arc, Mutex};

use axum::http::{HeaderMap, StatusCode};
use axum::Json;
use open_fdd_edge_prototype::auth::redact;
use serde::Serialize;
use serde_json::Value;

use crate::auth::{AuthUser, Role};

pub const AUDIT_SCHEMA: &str = "openfdd.audit.v1";
pub const MAX_ID_CHARS: usize = 128;
pub const MAX_REQUEST_ID_CHARS: usize = 64;
pub const MAX_PATH_CHARS: usize = 256;
pub const MAX_LIST_ITEMS: usize = 16;
pub const MAX_EVENT_BYTES: usize = 8 * 1024;

/// Server-side identity of the HTTP request being handled.
///
/// Clones share the attribution slot, so a bearer check and a later job enqueue
/// on the same request see one server id.
#[derive(Debug, Clone)]
pub struct RequestContext {
    /// Generated by central for every request. The audit primary key.
    pub server_id: String,
    /// Caller-supplied `x-request-id`, stored separately and bounded.
    pub caller_id: Option<String>,
    pub method: String,
    pub path: String,
    shared: Arc<RequestShared>,
}

#[derive(Debug)]
struct RequestShared {
    untrusted: Mutex<UntrustedLabels>,
    bearer: Mutex<Option<VerifiedActor>>,
    minted: Mutex<Option<VerifiedActor>>,
    jobs: Mutex<IdList>,
    receipts: Mutex<IdList>,
}

#[derive(Debug, Default, Clone)]
struct IdList {
    items: Vec<String>,
    total: usize,
}

impl RequestContext {
    pub fn new(caller_id: Option<&str>, method: &str, path: &str) -> Self {
        Self {
            server_id: uuid::Uuid::new_v4().to_string(),
            caller_id: caller_id
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(|s| redact::bounded(s, MAX_REQUEST_ID_CHARS)),
            method: redact::bounded(method, 16),
            path: redact::bounded(path, MAX_PATH_CHARS),
            shared: Arc::new(RequestShared {
                untrusted: Mutex::new(UntrustedLabels::default()),
                bearer: Mutex::new(None),
                minted: Mutex::new(None),
                jobs: Mutex::new(IdList::default()),
                receipts: Mutex::new(IdList::default()),
            }),
        }
    }

    /// Copy caller headers into the untrusted label slot.
    ///
    /// These values are never an identity, a session, or an approved QA run.
    pub fn with_untrusted_headers(self, headers: &HeaderMap) -> Self {
        if let Ok(mut labels) = self.shared.untrusted.lock() {
            *labels = UntrustedLabels::from_headers(headers);
        }
        self
    }
}

fn lock_mutex<T>(mutex: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

tokio::task_local! {
    static REQUEST_CONTEXT: RequestContext;
}

/// Run `fut` with `ctx` visible to every audit event built inside it.
pub async fn with_request_context<F: Future>(ctx: RequestContext, fut: F) -> F::Output {
    REQUEST_CONTEXT.scope(ctx, fut).await
}

fn current_context() -> Option<RequestContext> {
    REQUEST_CONTEXT.try_with(Clone::clone).ok()
}

/// How an actor is attributed. `auth_kind` stays the credential channel.
/// This class is the person, shared credential, or agent session.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum IdentityClass {
    UniqueHuman,
    SharedCredential,
    AgentSession,
    Anonymous,
}

impl IdentityClass {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::UniqueHuman => "unique_human",
            Self::SharedCredential => "shared_credential",
            Self::AgentSession => "agent_session",
            Self::Anonymous => "anonymous",
        }
    }

    pub fn parse(raw: &str) -> Option<Self> {
        match raw.trim() {
            "unique_human" => Some(Self::UniqueHuman),
            "shared_credential" => Some(Self::SharedCredential),
            "agent_session" => Some(Self::AgentSession),
            "anonymous" => Some(Self::Anonymous),
            _ => None,
        }
    }
}

/// Classification stored on a newly minted token (`ak` claim).
pub fn identity_class_for_new_session(sub: &str, uid: Option<&str>) -> IdentityClass {
    match sub.trim().to_ascii_lowercase().as_str() {
        "agent" => IdentityClass::AgentSession,
        "dev" => IdentityClass::Anonymous,
        "admin" | "viewer" => IdentityClass::SharedCredential,
        _ => {
            if uid.map(str::trim).is_some_and(|id| !id.is_empty()) || !sub.trim().is_empty() {
                IdentityClass::UniqueHuman
            } else {
                IdentityClass::Anonymous
            }
        }
    }
}

/// Server-verified actor. Headers cannot construct this value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VerifiedActor {
    pub class: IdentityClass,
    pub actor_id: Option<String>,
    pub subject: String,
    pub session_id: Option<String>,
    pub delegated_by: Option<String>,
    pub expires_at: Option<String>,
}

impl VerifiedActor {
    pub fn from_token_claims(
        sub: &str,
        uid: Option<&str>,
        session_id: Option<&str>,
        delegated_by: Option<&str>,
        class_claim: Option<&str>,
        expires_at: Option<String>,
    ) -> Self {
        let class = class_claim
            .and_then(IdentityClass::parse)
            .unwrap_or_else(|| classify_legacy_subject(sub, uid, session_id));
        let actor_id = match class {
            IdentityClass::UniqueHuman => uid
                .map(str::trim)
                .filter(|id| !id.is_empty())
                .map(str::to_string)
                .or_else(|| {
                    let subject = sub.trim();
                    (!subject.is_empty()).then(|| subject.to_string())
                }),
            _ => None,
        };
        Self {
            class,
            actor_id,
            subject: sub.trim().to_string(),
            session_id: session_id
                .map(str::trim)
                .filter(|id| !id.is_empty())
                .map(str::to_string),
            delegated_by: delegated_by
                .map(str::trim)
                .filter(|id| !id.is_empty())
                .map(str::to_string),
            expires_at,
        }
    }
}

fn classify_legacy_subject(
    sub: &str,
    uid: Option<&str>,
    session_id: Option<&str>,
) -> IdentityClass {
    match sub.trim().to_ascii_lowercase().as_str() {
        "dev" => IdentityClass::Anonymous,
        "admin" | "viewer" => IdentityClass::SharedCredential,
        "agent" => {
            if session_id.map(str::trim).is_some_and(|id| !id.is_empty()) {
                IdentityClass::AgentSession
            } else {
                IdentityClass::SharedCredential
            }
        }
        _ => {
            if sub.trim().is_empty() {
                IdentityClass::Anonymous
            } else if uid.map(str::trim).is_some_and(|id| !id.is_empty()) || !sub.trim().is_empty()
            {
                IdentityClass::UniqueHuman
            } else {
                IdentityClass::Anonymous
            }
        }
    }
}

/// Caller-supplied header values. Never copied into `identity` or `qa_run`.
#[derive(Debug, Clone, Default, Serialize)]
struct UntrustedLabels {
    #[serde(skip_serializing_if = "Option::is_none")]
    user_agent: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    forwarded_for: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    claimed_qa_run: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    claimed_actor: Option<String>,
}

impl UntrustedLabels {
    fn from_headers(headers: &HeaderMap) -> Self {
        Self {
            user_agent: header_label(headers, "user-agent", MAX_ID_CHARS),
            forwarded_for: header_label(headers, "x-forwarded-for", MAX_ID_CHARS),
            claimed_qa_run: header_label(headers, "x-openfdd-qa-run", MAX_REQUEST_ID_CHARS),
            claimed_actor: header_label(headers, "x-openfdd-actor", MAX_ID_CHARS),
        }
    }
}

fn header_label(headers: &HeaderMap, name: &'static str, cap: usize) -> Option<String> {
    let raw = headers.get(name)?.to_str().ok()?.trim();
    if raw.is_empty() {
        return None;
    }
    Some(redact::bounded(raw, cap))
}

#[derive(Debug, Clone, Serialize)]
struct IdentityRecord {
    class: IdentityClass,
    #[serde(skip_serializing_if = "Option::is_none")]
    actor_id: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    subject: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    session_id: Option<String>,
    issuer: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    delegated_by: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    expires_at: Option<String>,
}

impl IdentityRecord {
    fn anonymous() -> Self {
        Self {
            class: IdentityClass::Anonymous,
            actor_id: None,
            subject: None,
            session_id: None,
            issuer: ISSUER,
            delegated_by: None,
            expires_at: None,
        }
    }

    fn from_actor(actor: &VerifiedActor) -> Self {
        Self {
            class: actor.class,
            actor_id: actor
                .actor_id
                .as_deref()
                .map(|id| redact::bounded(id, MAX_ID_CHARS)),
            subject: Some(redact::bounded(&actor.subject, MAX_ID_CHARS)),
            session_id: actor
                .session_id
                .as_deref()
                .map(|id| redact::bounded(id, MAX_REQUEST_ID_CHARS)),
            issuer: ISSUER,
            delegated_by: actor
                .delegated_by
                .as_deref()
                .map(|id| redact::bounded(id, MAX_REQUEST_ID_CHARS)),
            expires_at: actor
                .expires_at
                .as_deref()
                .map(|ts| redact::bounded(ts, MAX_ID_CHARS)),
        }
    }
}

