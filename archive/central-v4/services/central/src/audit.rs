/// Handler result shape shared by the audited routes.
pub type HandlerResult = Result<Json<Value>, (StatusCode, Json<Value>)>;

/// One `openfdd.audit.v1` record. Build it at the start of an operation,
/// fill it as the request is resolved, and emit it once the result is known.
#[derive(Debug, Clone, Serialize)]
pub struct AuditEvent {
    schema: &'static str,
    ts: String,
    request_id: String,
    caller_request_id: Option<String>,
    action: AuditAction,
    actor: Option<String>,
    auth_kind: AuthKind,
    role: Option<AuditRole>,
    tenant_id: Option<String>,
    site_id: Option<String>,
    target_type: Option<TargetType>,
    target_id: Option<String>,
    change: Option<AuditChange>,
    decision: Decision,
    reason: Option<ReasonCode>,
    outcome: Outcome,
    http_status: Option<u16>,
    method: Option<String>,
    path: Option<String>,
    build: String,
    truncated: bool,
    identity: IdentityRecord,
    qa_run: Option<QaRunRecord>,
    untrusted_labels: UntrustedLabels,
    correlation: CorrelationRecord,
    issued_session: Option<IssuedSession>,
}

impl AuditEvent {
    pub fn new(action: AuditAction) -> Self {
        let ctx = current_context();
        let (request_id, caller_request_id, method, path) = match ctx {
            Some(ctx) => (
                ctx.server_id,
                ctx.caller_id,
                Some(ctx.method),
                Some(ctx.path),
            ),
            None => (uuid::Uuid::new_v4().to_string(), None, None, None),
        };
        Self {
            schema: AUDIT_SCHEMA,
            ts: chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Millis, true),
            request_id,
            caller_request_id,
            action,
            actor: None,
            auth_kind: AuthKind::Anonymous,
            role: None,
            tenant_id: None,
            site_id: None,
            target_type: None,
            target_id: None,
            change: None,
            decision: Decision::Allow,
            reason: None,
            outcome: Outcome::Failed,
            http_status: None,
            method,
            path,
            build: redact::bounded(
                &crate::routes::resolve_build_version(),
                MAX_REQUEST_ID_CHARS,
            ),
            truncated: false,
            identity: IdentityRecord::anonymous(),
            qa_run: None,
            untrusted_labels: UntrustedLabels::default(),
            correlation: CorrelationRecord {
                server_request_id: String::new(),
                job_ids: BoundedList::new(&[] as &[String]),
                receipt_ids: BoundedList::new(&[] as &[String]),
            },
            issued_session: None,
        }
    }

    fn refresh_attribution(&mut self) {
        let ctx = current_context();
        let (bearer, minted, untrusted, jobs, receipts, server_id) = match ctx.as_ref() {
            Some(ctx) => (
                lock_mutex(&ctx.shared.bearer).clone(),
                lock_mutex(&ctx.shared.minted).clone(),
                lock_mutex(&ctx.shared.untrusted).clone(),
                lock_mutex(&ctx.shared.jobs).clone(),
                lock_mutex(&ctx.shared.receipts).clone(),
                ctx.server_id.clone(),
            ),
            None => (
                None,
                None,
                UntrustedLabels::default(),
                IdList::default(),
                IdList::default(),
                self.request_id.clone(),
            ),
        };
        let (identity, issued) = match (bearer, minted) {
            (Some(caller), Some(minted)) if caller.session_id != minted.session_id => (
                IdentityRecord::from_actor(&caller),
                minted.session_id.as_ref().map(|session_id| IssuedSession {
                    class: minted.class,
                    session_id: redact::bounded(session_id, MAX_REQUEST_ID_CHARS),
                    delegated_by: minted
                        .delegated_by
                        .as_deref()
                        .map(|id| redact::bounded(id, MAX_REQUEST_ID_CHARS)),
                    expires_at: minted
                        .expires_at
                        .as_deref()
                        .map(|ts| redact::bounded(ts, MAX_ID_CHARS)),
                }),
            ),
            (_, Some(minted)) => (IdentityRecord::from_actor(&minted), None),
            (Some(caller), None) => (IdentityRecord::from_actor(&caller), None),
            (None, None) => (self.identity_from_subject(), None),
        };
        self.identity = identity;
        self.issued_session = issued;
        self.untrusted_labels = untrusted;
        // A manifest tags an authenticated caller. Anonymous traffic, including
        // a client `x-openfdd-qa-run` label, does not receive `qa_run`.
        self.qa_run = match self.identity.class {
            IdentityClass::Anonymous => None,
            _ => server_qa_run(),
        };
        self.correlation = CorrelationRecord {
            server_request_id: server_id,
            job_ids: BoundedList {
                items: jobs.items.iter().take(MAX_LIST_ITEMS).cloned().collect(),
                total: jobs.total,
                truncated: jobs.total > MAX_LIST_ITEMS,
            },
            receipt_ids: BoundedList {
                items: receipts
                    .items
                    .iter()
                    .take(MAX_LIST_ITEMS)
                    .cloned()
                    .collect(),
                total: receipts.total,
                truncated: receipts.total > MAX_LIST_ITEMS,
            },
        };
    }

    fn identity_from_subject(&self) -> IdentityRecord {
        let Some(subject) = self.actor.as_deref() else {
            return IdentityRecord::anonymous();
        };
        let class = classify_legacy_subject(subject, None, None);
        IdentityRecord {
            class,
            actor_id: match class {
                IdentityClass::UniqueHuman => Some(redact::bounded(subject, MAX_ID_CHARS)),
                _ => None,
            },
            subject: Some(redact::bounded(subject, MAX_ID_CHARS)),
            session_id: None,
            issuer: ISSUER,
            delegated_by: None,
            expires_at: None,
        }
    }

    fn acknowledged(&self) -> bool {
        if self.decision == Decision::Deny {
            return true;
        }
        !matches!(
            self.action,
            AuditAction::AuthBearer | AuditAction::AdminRead | AuditAction::SiteAccess
        )
    }

    fn bound(&mut self, raw: &str) -> Option<String> {
        let raw = raw.trim();
        if raw.is_empty() {
            return None;
        }
        let b = redact::bounded_text(raw, MAX_ID_CHARS);
        self.truncated |= b.truncated;
        Some(b.text)
    }

    /// Actor, role, auth kind, and active tenant from an authenticated caller.
    pub fn user(&mut self, user: &AuthUser) -> &mut Self {
        self.actor(&user.sub);
        self.auth_kind = AuthKind::for_subject(&user.sub);
        self.role = Some(user.role.into());
        let tenant = user
            .active_tenant_id
            .as_deref()
            .or_else(|| user.tenant_ids.first().map(String::as_str));
        self.tenant(tenant)
    }

    pub fn actor(&mut self, sub: &str) -> &mut Self {
        self.actor = self.bound(sub);
        self.auth_kind = AuthKind::for_subject(sub);
        self
    }

    /// Copy the verified bearer subject when the handler does not have `AuthUser`.
    ///
    /// A missing request scope or an anonymous caller leaves `actor` unchanged.
    pub fn note_request_actor(&mut self) -> &mut Self {
        let Some(ctx) = current_context() else {
            return self;
        };
        let subject = lock_mutex(&ctx.shared.bearer)
            .as_ref()
            .map(|actor| actor.subject.clone());
        if let Some(subject) = subject.as_deref() {
            self.actor(subject);
        }
        self
    }

    pub fn role(&mut self, role: Role) -> &mut Self {
        self.role = Some(role.into());
        self
    }

    pub fn tenant(&mut self, tenant_id: Option<&str>) -> &mut Self {
        self.tenant_id = tenant_id.and_then(|t| self.bound(t));
        self
    }

    pub fn site(&mut self, site_id: &str) -> &mut Self {
        self.site_id = self.bound(site_id);
        self
    }

    pub fn target(&mut self, kind: TargetType, id: &str) -> &mut Self {
        self.target_type = Some(kind);
        self.target_id = self.bound(id);
        self
    }

    pub fn target_type(&mut self, kind: TargetType) -> &mut Self {
        self.target_type = Some(kind);
        self
    }

    /// Route target from the current request path (no query string).
    pub fn target_route(&mut self) -> &mut Self {
        match current_context() {
            Some(ctx) => self.target(TargetType::Route, &ctx.path),
            None => self.target_type(TargetType::Route),
        }
    }

    /// Site target that also sets `site_id`.
    pub fn target_site(&mut self, building_id: &str) -> &mut Self {
        self.site(building_id);
        self.target(TargetType::Site, building_id)
    }

    pub fn change(&mut self, change: AuditChange) -> &mut Self {
        self.change = Some(change);
        self
    }

    pub fn deny(&mut self, reason: ReasonCode) -> &mut Self {
        self.decision = Decision::Deny;
        self.reason = Some(reason);
        self.outcome = Outcome::Failed;
        self
    }

    /// Failure reason for an allowed operation that did not complete.
    pub fn reason(&mut self, reason: ReasonCode) -> &mut Self {
        self.reason = Some(reason);
        self
    }

    pub fn outcome(&mut self, outcome: Outcome) -> &mut Self {
        self.outcome = outcome;
        self
    }

    pub fn status(&mut self, status: StatusCode) -> &mut Self {
        self.http_status = Some(status.as_u16());
        self
    }

    pub fn is_denied(&self) -> bool {
        self.decision == Decision::Deny
    }

    /// Derive status, decision, and outcome from the handler result.
    ///
    /// A 401/403 that no check recorded becomes a deny. A body with
    /// `"ok": true` is `ok` unless the handler already marked it partial or
    /// replayed.
    pub fn finish(&mut self, result: &HandlerResult) -> &mut Self {
        self.finish_typed(result);
        if let Ok(Json(body)) = result {
            let ok = body.get("ok").and_then(Value::as_bool).unwrap_or(false);
            if !ok && self.outcome != Outcome::Partial {
                self.outcome = Outcome::Failed;
            }
        }
        self
    }

    /// [`Self::finish`] for typed response bodies: any `Ok` is success.
    pub fn finish_typed<T>(&mut self, result: &Result<T, (StatusCode, Json<Value>)>) -> &mut Self {
        match result {
            Ok(_) => {
                self.status(StatusCode::OK);
                if !matches!(self.outcome, Outcome::Partial | Outcome::Replayed) {
                    self.outcome = Outcome::Ok;
                }
            }
            Err((status, _)) => {
                self.status(*status);
                if !self.is_denied()
                    && matches!(*status, StatusCode::UNAUTHORIZED | StatusCode::FORBIDDEN)
                {
                    let reason = self.reason.unwrap_or(ReasonCode::from_status(*status));
                    self.deny(reason);
                }
                if self.outcome != Outcome::Partial {
                    self.outcome = Outcome::Failed;
                }
                if self.reason.is_none() {
                    self.reason = Some(ReasonCode::from_status(*status));
                }
            }
        }
        self
    }

    /// Serialized record, bounded by [`MAX_EVENT_BYTES`].
    pub fn to_value(&self) -> Value {
        let mut owned = self.clone();
        owned.refresh_attribution();
        let full = serde_json::to_value(&owned).unwrap_or(Value::Null);
        if !full.is_null() && full.to_string().len() <= MAX_EVENT_BYTES {
            return full;
        }
        let mut reduced = owned;
        reduced.change = None;
        reduced.path = None;
        reduced.truncated = true;
        serde_json::to_value(&reduced)
            .ok()
            .filter(|v| v.to_string().len() <= MAX_EVENT_BYTES)
            .unwrap_or_else(|| {
                serde_json::json!({
                    "schema": AUDIT_SCHEMA,
                    "request_id": self.request_id,
                    "action": self.action,
                    "decision": self.decision,
                    "outcome": self.outcome,
                    "truncated": true,
                })
            })
    }

    pub fn emit(&self) {
        let value = self.to_value();
        if self.acknowledged() {
            // A false result is already on the loss ledger and `/api/health`.
            // The handler still returns the operation result it already computed.
            let _durable = open_fdd_edge_prototype::auth::audit::log_event_acknowledged(
                self.action.as_str(),
                value,
            );
        } else {
            open_fdd_edge_prototype::auth::audit::log_event(self.action.as_str(), value);
        }
    }
}

/// Bearer rejection in the JWT middleware or a handler that re-verifies.
pub fn bearer_rejected(detail: &str, status: StatusCode) {
    let mut ev = AuditEvent::new(AuditAction::AuthBearer);
    ev.target_route()
        .deny(ReasonCode::from_auth_detail(detail))
        .status(status)
        .emit();
}

/// Role or hub-admin denial for an authenticated caller.
pub fn role_denied(user: &AuthUser, action: AuditAction, reason: ReasonCode) -> AuditEvent {
    let mut ev = AuditEvent::new(action);
    ev.user(user).deny(reason).status(StatusCode::FORBIDDEN);
    ev
}

