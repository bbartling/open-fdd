/// Safe, enumerable reason. Never a free-form error string.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ReasonCode {
    MissingCredentials,
    MalformedAuthorization,
    InvalidToken,
    ExpiredToken,
    RevokedSession,
    IdentityDisabled,
    IdentityUnknown,
    IdentityStoreUnavailable,
    InvalidCredentials,
    RateLimited,
    RoleRequired,
    HubAdminRequired,
    TenantScope,
    SiteScope,
    SiteRequired,
    SizeCap,
    AdmissionShed,
    InvalidRequest,
    NotFound,
    /// Compare-and-swap precondition failed (`409`).
    RevisionConflict,
    StorageError,
    HistorianError,
    InternalError,
}

impl ReasonCode {
    /// Map a bearer verification error from [`crate::auth`] to a reason code.
    pub fn from_auth_detail(detail: &str) -> Self {
        use crate::auth::{
            AUTH_HEADER_MALFORMED, AUTH_HEADER_MISSING, IDENTITY_DISABLED,
            IDENTITY_STORE_UNAVAILABLE, IDENTITY_UNKNOWN, SESSION_REVOKED, TOKEN_EXPIRED,
        };
        match detail {
            AUTH_HEADER_MISSING => Self::MissingCredentials,
            AUTH_HEADER_MALFORMED => Self::MalformedAuthorization,
            TOKEN_EXPIRED => Self::ExpiredToken,
            SESSION_REVOKED => Self::RevokedSession,
            IDENTITY_DISABLED => Self::IdentityDisabled,
            IDENTITY_UNKNOWN => Self::IdentityUnknown,
            IDENTITY_STORE_UNAVAILABLE => Self::IdentityStoreUnavailable,
            _ => Self::InvalidToken,
        }
    }

    fn from_status(status: StatusCode) -> Self {
        match status {
            StatusCode::UNAUTHORIZED => Self::InvalidToken,
            StatusCode::FORBIDDEN => Self::RoleRequired,
            StatusCode::NOT_FOUND => Self::NotFound,
            StatusCode::TOO_MANY_REQUESTS => Self::AdmissionShed,
            StatusCode::SERVICE_UNAVAILABLE => Self::HistorianError,
            s if s.is_client_error() => Self::InvalidRequest,
            _ => Self::InternalError,
        }
    }
}

