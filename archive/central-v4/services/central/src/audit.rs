const ISSUER: &str = "openfdd-central";
const QA_MANIFEST_ENV: &str = "OPENFDD_QA_RUN_MANIFEST";

struct QaCache {
    path: String,
    mtime_key: Option<u128>,
    record: Option<QaRunRecord>,
}

fn qa_cache() -> std::sync::MutexGuard<'static, Option<QaCache>> {
    static CACHE: std::sync::OnceLock<Mutex<Option<QaCache>>> = std::sync::OnceLock::new();
    CACHE
        .get_or_init(|| Mutex::new(None))
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

fn server_qa_run() -> Option<QaRunRecord> {
    let path = std::env::var(QA_MANIFEST_ENV)
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())?;
    let mtime_key = std::fs::metadata(&path)
        .ok()
        .and_then(|meta| meta.modified().ok())
        .and_then(|modified| modified.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|duration| duration.as_nanos());
    {
        let cache = qa_cache();
        if let Some(cached) = cache.as_ref() {
            if cached.path == path && cached.mtime_key == mtime_key {
                return cached.record.clone();
            }
        }
    }
    let record = read_qa_manifest(&path);
    *qa_cache() = Some(QaCache {
        path,
        mtime_key,
        record: record.clone(),
    });
    record
}

fn read_qa_manifest(path: &str) -> Option<QaRunRecord> {
    let text = std::fs::read_to_string(path).ok()?;
    let value: Value = serde_json::from_str(&text).ok()?;
    let run_id = value.get("run_id").and_then(Value::as_str)?.trim();
    if run_id.is_empty() {
        return None;
    }
    let window_start = value.get("window_start").and_then(Value::as_str)?.trim();
    let window_end = value.get("window_end").and_then(Value::as_str)?.trim();
    let start = chrono::DateTime::parse_from_rfc3339(window_start)
        .ok()?
        .with_timezone(&chrono::Utc);
    let end = chrono::DateTime::parse_from_rfc3339(window_end)
        .ok()?
        .with_timezone(&chrono::Utc);
    let now = chrono::Utc::now();
    if now < start || now > end {
        return None;
    }
    let tenants = string_list(value.get("tenants"));
    let sites = string_list(value.get("sites"));
    let tool_version = value
        .get("tool_version")
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|text| !text.is_empty())
        .map(|text| redact::bounded(text, MAX_ID_CHARS));
    let candidate = value
        .get("candidate")
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|text| !text.is_empty())
        .map(|text| redact::bounded(text, MAX_ID_CHARS));
    Some(QaRunRecord {
        run_id: redact::bounded(run_id, MAX_REQUEST_ID_CHARS),
        server_approved: true,
        tenants: BoundedList::new(&tenants),
        sites: BoundedList::new(&sites),
        tool_version,
        candidate,
        window_start: Some(redact::bounded(window_start, MAX_ID_CHARS)),
        window_end: Some(redact::bounded(window_end, MAX_ID_CHARS)),
    })
}

fn string_list(value: Option<&Value>) -> Vec<String> {
    value
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .map(str::trim)
                .filter(|item| !item.is_empty())
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default()
}

/// Record the verified bearer for this request. No request scope is a no-op.
pub fn note_verified_bearer(actor: VerifiedActor) {
    let Ok(ctx) = REQUEST_CONTEXT.try_with(Clone::clone) else {
        return;
    };
    *lock_mutex(&ctx.shared.bearer) = Some(actor);
}

/// Record the session minted by this request. No request scope is a no-op.
pub fn note_minted_session(actor: VerifiedActor) {
    let Ok(ctx) = REQUEST_CONTEXT.try_with(Clone::clone) else {
        return;
    };
    *lock_mutex(&ctx.shared.minted) = Some(actor);
}

/// Parent session id of the verified bearer, when this request has one.
pub fn bearer_session_id() -> Option<String> {
    let ctx = current_context()?;
    let session = lock_mutex(&ctx.shared.bearer)
        .as_ref()
        .and_then(|actor| actor.session_id.clone());
    session
}

/// Server id for the active request, when the caller is inside request scope.
pub fn current_server_request_id() -> Option<String> {
    current_context().map(|ctx| ctx.server_id)
}

/// Attach a job id to the active request. Scheduler work with no request is unchanged.
pub fn correlate_job(job_id: &str) {
    let Ok(ctx) = REQUEST_CONTEXT.try_with(Clone::clone) else {
        return;
    };
    let mut ids = lock_mutex(&ctx.shared.jobs);
    ids.total = ids.total.saturating_add(1);
    if ids.items.len() < 256 {
        ids.items.push(redact::bounded(job_id, MAX_ID_CHARS));
    }
}

/// Attach a receipt id to the active request.
pub fn correlate_receipt(receipt_id: &str) {
    let Ok(ctx) = REQUEST_CONTEXT.try_with(Clone::clone) else {
        return;
    };
    let mut ids = lock_mutex(&ctx.shared.receipts);
    ids.total = ids.total.saturating_add(1);
    if ids.items.len() < 256 {
        ids.items.push(redact::bounded(receipt_id, MAX_ID_CHARS));
    }
}

