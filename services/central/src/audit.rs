/// Bounded list of identifiers (tenant ids, building ids, action ids).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct BoundedList {
    pub items: Vec<String>,
    pub total: usize,
    pub truncated: bool,
}

impl BoundedList {
    pub fn new<S: AsRef<str>>(items: &[S]) -> Self {
        let mut truncated = items.len() > MAX_LIST_ITEMS;
        let kept = items
            .iter()
            .take(MAX_LIST_ITEMS)
            .map(|item| {
                let b = redact::bounded_text(item.as_ref(), MAX_ID_CHARS);
                truncated |= b.truncated;
                b.text
            })
            .collect();
        Self {
            items: kept,
            total: items.len(),
            truncated,
        }
    }
}

/// What a write changed. Counts, flags, and bounded id lists only.
#[derive(Debug, Clone, PartialEq, Serialize)]
