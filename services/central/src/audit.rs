//! Typed security audit events (`openfdd.audit.v1`).
//!
//! Each sensitive operation builds one [`AuditEvent`] and emits it after the
//! result is known, including error paths. Fields are an allowlist: identifiers,
//! enums, and counts. Request bodies, headers, tokens, and passwords are never
//! fields. Every string goes through [`open_fdd_edge_prototype::auth::redact`]
//! with a fixed budget, and the serialized event is bounded by [`MAX_EVENT_BYTES`].
//!
//! The sink is still `open_fdd_edge_prototype::auth::audit::log_event`;
//! [`AuditEvent::emit`] is the only call into it from this module, so the writer
//! can be replaced without touching handlers.

use std::future::Future;

use axum::http::StatusCode;
use axum::Json;
use open_fdd_edge_prototype::auth::redact;
use serde::Serialize;
use serde_json::Value;

use crate::auth::{AuthUser, Role};

pub const AUDIT_SCHEMA: &str = "openfdd.audit.v1";
pub const MAX_ID_CHARS: usize = 128;
pub const MAX_REQUEST_ID_CHARS: usize = 64;
pub const MAX_PATH_CHARS: usize = 256;
pub const MAX_LIST_ITEMS: usize = 16;
pub const MAX_EVENT_BYTES: usize = 8 * 1024;

/// Server-side identity of the HTTP request being handled.
#[derive(Debug, Clone)]
pub struct RequestContext {
    /// Generated by central for every request. The audit primary key.
    pub server_id: String,
    /// Caller-supplied `x-request-id`, stored separately and bounded.
    pub caller_id: Option<String>,
    pub method: String,
    pub path: String,
}

impl RequestContext {
    pub fn new(caller_id: Option<&str>, method: &str, path: &str) -> Self {
        Self {
            server_id: uuid::Uuid::new_v4().to_string(),
            caller_id: caller_id
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(|s| redact::bounded(s, MAX_REQUEST_ID_CHARS)),
            method: redact::bounded(method, 16),
            path: redact::bounded(path, MAX_PATH_CHARS),
        }
    }
}

tokio::task_local! {
    static REQUEST_CONTEXT: RequestContext;
}

/// Run `fut` with `ctx` visible to every audit event built inside it.
pub async fn with_request_context<F: Future>(ctx: RequestContext, fut: F) -> F::Output {
    REQUEST_CONTEXT.scope(ctx, fut).await
}

fn current_context() -> Option<RequestContext> {
    REQUEST_CONTEXT.try_with(Clone::clone).ok()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AuthKind {
    HumanLogin,
    AgentToken,
    Anonymous,
}

impl AuthKind {
    /// `agent` is the operator identity minted for MCP / AI hosts; `dev` is
    /// open-mode anonymous. Both are reserved env identities.
    pub fn for_subject(sub: &str) -> Self {
        match sub.trim().to_ascii_lowercase().as_str() {
            "agent" => Self::AgentToken,
            "dev" => Self::Anonymous,
            _ => Self::HumanLogin,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AuditRole {
    Viewer,
    Operator,
    Admin,
}

impl From<Role> for AuditRole {
    fn from(role: Role) -> Self {
        match role {
            Role::Viewer => Self::Viewer,
            Role::Operator => Self::Operator,
            Role::Admin => Self::Admin,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Decision {
    Allow,
    Deny,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Outcome {
    Ok,
    Failed,
    Partial,
    Replayed,
}

/// Safe, enumerable reason. Never a free-form error string.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ReasonCode {
    MissingCredentials,
    MalformedAuthorization,
    InvalidToken,
    ExpiredToken,
    RevokedSession,
    IdentityDisabled,
    IdentityUnknown,
    IdentityStoreUnavailable,
    InvalidCredentials,
    RateLimited,
    RoleRequired,
    HubAdminRequired,
    TenantScope,
    SiteScope,
    SiteRequired,
    SizeCap,
    AdmissionShed,
    InvalidRequest,
    NotFound,
    StorageError,
    HistorianError,
    InternalError,
}

impl ReasonCode {
    /// Map a bearer verification error from [`crate::auth`] to a reason code.
    pub fn from_auth_detail(detail: &str) -> Self {
        use crate::auth::{
            AUTH_HEADER_MALFORMED, AUTH_HEADER_MISSING, IDENTITY_DISABLED,
            IDENTITY_STORE_UNAVAILABLE, IDENTITY_UNKNOWN, SESSION_REVOKED, TOKEN_EXPIRED,
        };
        match detail {
            AUTH_HEADER_MISSING => Self::MissingCredentials,
            AUTH_HEADER_MALFORMED => Self::MalformedAuthorization,
            TOKEN_EXPIRED => Self::ExpiredToken,
            SESSION_REVOKED => Self::RevokedSession,
            IDENTITY_DISABLED => Self::IdentityDisabled,
            IDENTITY_UNKNOWN => Self::IdentityUnknown,
            IDENTITY_STORE_UNAVAILABLE => Self::IdentityStoreUnavailable,
            _ => Self::InvalidToken,
        }
    }

    fn from_status(status: StatusCode) -> Self {
        match status {
            StatusCode::UNAUTHORIZED => Self::InvalidToken,
            StatusCode::FORBIDDEN => Self::RoleRequired,
            StatusCode::NOT_FOUND => Self::NotFound,
            StatusCode::TOO_MANY_REQUESTS => Self::AdmissionShed,
            StatusCode::SERVICE_UNAVAILABLE => Self::HistorianError,
            s if s.is_client_error() => Self::InvalidRequest,
            _ => Self::InternalError,
        }
    }
}

