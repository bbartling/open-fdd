def normalize_haystack_slug(point: str) -> str:
    slug = point.strip().lower().replace(" ", "-").replace("_", "-")
    slug = slug.replace("-temperature", "-temp")
    slug = slug.replace("-setpoint", "-sp")
    if slug.endswith("-active") and "-sp" in slug:
        slug = slug[: -len("-active")]
    if slug.startswith("hw-"):
        slug = "hot-water-" + slug[3:]
    elif slug.startswith("chw-"):
        slug = "chilled-water-" + slug[4:]
    if slug.endswith("-local"):
        slug = slug[: -len("-local")]
    return slug


def normalize_role(role: str) -> str:
    key = role.strip().lower()
    return ROLE_CANDIDATES.get(key, key)


def haystack_point_to_role(point: str) -> str:
    raw = point.strip().lower()
    if "_" in raw:
        role = normalize_role(raw)
        if role in KNOWN_COOKBOOK_ROLES:
            return role
    slug = normalize_haystack_slug(point)
    if slug in _HAYSTACK_SLUG_TO_ROLE:
        return _HAYSTACK_SLUG_TO_ROLE[slug]
    return normalize_role(slug.replace("-", "_"))
